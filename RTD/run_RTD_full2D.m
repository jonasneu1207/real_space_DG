function [results,mat] = run_RTD_full2D(options)
%RUN_RTD_FULL2D Constant-mass RTD with periodic Y and open X contacts.
% options: Ly,dy in nm, bias in V, removeBarriers (logical), dg (overrides).
% simulation='flatband' (default) or 'self-consistent'. For self-consistency,
% options.selfConsistent.poissonMethod selects direct or newton-raphson.
% An optional poissonStep callback overrides the built-in Poisson solver.
if nargin < 1, options = struct; end
rtdDir = fileparts(mfilename('fullpath'));
originalPath = path;
restorePath = onCleanup(@() path(originalPath));
addpath(rtdDir,fullfile(fileparts(rtdDir),'DG_code'), ...
    fullfile(fileparts(rtdDir),'DG_code','core'));
width = option(options,'Ly',5);
mat = buildDevice2D_rtd('n-RTD-constM-comp',width,option(options,'dy',0.5));
mat.Vdd = option(options,'bias',0);
validateattributes(mat.Vdd,{'numeric'},{'real','finite','nonempty','vector'});
if option(options,'removeBarriers',false)
    mat.Vc(:) = mat.Vc(1,1);
    mat.V = mat.Vc;
end
params = struct('full2D',true,'N_K_X',3,'N_K_Y',3, ...
    'N_el_X',32,'N_el_Y',2,'N_rho_x',80,'N_rho_y',24, ...
    'L_rho_x',80e-9,'L_rho_y',2*width*1e-9, ...
    'full2D_Y_boundary','periodic','full2D_massModel','constant', ...
    'full2D_X_flux','upwind','full2D_Y_flux','upwind', ...
    'full2D_reservoirModel','contact-modes', ...
    'full2D_contactModeFermiModel','contact-neutrality', ...
    'full2D_contactModeIntegrateKz',true, ...
    'full2D_contactMode_Nkx',160,'full2D_contactMode_Nkz',201, ...
    'full2D_sourceContactSheetDensity',trapz(mat.y*1e-9,mat.Nd(1,:)), ...
    'full2D_drainContactSheetDensity',trapz(mat.y*1e-9,mat.Nd(end,:)), ...
    'full2D_sourceContactMask',true(mat.Ny,1), ...
    'full2D_drainContactMask',true(mat.Ny,1), ...
    'full2D_potentialDiscretization','fv-consistent', ...
    'full2D_potentialQuadratureOrder',5,'full2D_cap_scale',1, ...
    'full2D_assembleDiffMatrix',false,'full2D_assembleDriftMatrix',false, ...
    'full2D_solve',true,'full2D_solver','gmres','full2D_gpu',false, ...
    'full2D_preconditioner','line-transverse','full2D_gmresRestart',80, ...
    'full2D_lineRelativeShift',0.03, ...
    'full2D_solverTol',1e-3,'full2D_solverMaxIt',150, ...
    'full2D_showSolverProgress',true);
simulation = option(options,'simulation','flatband');
if strcmpi(simulation,'self-consistent')
    params.full2D_solverTol = 5e-6; % tighter default for coupled charge convergence
end
overrides = option(options,'dg',struct);
fields = fieldnames(overrides);
for k = 1:numel(fields)
    params.(fields{k}) = overrides.(fields{k});     % Jedes Feld in params, das bereits durch options (also in der main) definiert wurde, wird hier mit dem Wert aus options überschrieben
end
mat.dg.params = params;
switch lower(char(simulation))
    case 'flatband'
        results = solve2D_rtd_stat_flatband('DG',mat);
    case 'self-consistent'
        results = solve2D_rtd_self_consistent('DG',mat,option(options,'selfConsistent',struct));
    otherwise
        error('RTD:UnsupportedSimulation','Unknown simulation type: %s.',simulation);
end
results.mat = mat;
end

function value = option(options,name,default)
value = default;
if isfield(options,name), value = options.(name); end
end
